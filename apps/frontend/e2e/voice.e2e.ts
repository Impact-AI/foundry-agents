import { expect, test } from "@playwright/test";
import { composer, expectAccessible, signIn } from "./fixtures";

// A microphone that needs no device: a tone from Web Audio, handed to the
// page as `getUserMedia`'s stream before any of its scripts run. Chromium's
// fake capture device hangs where the OS gates the microphone (macOS), and
// a tone is all the stand-in needs. The backend's dev-fake stands the voice
// agent in at its socket and plays one spoken turn once the person's audio
// has begun to arrive, so what this proves is the whole path: the page's
// socket to this app's origin, the server's relay to the backend under the
// caller's assertion, the microphone's audio through the capture worklet to
// the voice agent, the voice's audio and words back, a stage control run in
// the browser and answered, the end, and the thread.
test.beforeEach(async ({ context }) => {
	await context.addInitScript(() => {
		const tone = async () => {
			const audio = new AudioContext();
			const oscillator = audio.createOscillator();
			const sink = audio.createMediaStreamDestination();
			oscillator.connect(sink);
			oscillator.start();
			return sink.stream;
		};
		Object.defineProperty(navigator, "mediaDevices", {
			value: { getUserMedia: tone },
			configurable: true,
		});
	});
});

const ASKED = "What happens on my first day?";
const ANSWERED = /you collect your badge and meet your buddy/;
const TYPED = [
	"And on the second day?",
	"Who signs my contract?",
	"Where do I park?",
	"When is lunch?",
];

test("live voice in the composer's place: the AI notice, the spoken turn written as it is said, the stage driven, and the turn in the chat once the channel closes", async ({
	page,
}) => {
	await signIn(page);
	await page.getByRole("button", { name: "Open the channel" }).click();
	const pane = page.getByRole("region", { name: "Voice" });
	await expect(pane).toBeVisible();
	await expect(
		pane.getByText(
			"This voice is generated by a computer. The assistant is an AI.",
		),
	).toBeVisible();
	await expect(pane.getByText("Live voice")).toBeVisible();
	// Voice or chat, never both.
	await expect(composer(page)).toHaveCount(0);

	// The turn the stand-in plays: heard, answered, and the document it opened on the stage.
	await expect(pane.getByText(ASKED)).toBeVisible();
	await expect(pane.getByText(ANSWERED)).toBeVisible();
	await expect(
		page.getByRole("main").getByRole("region", { name: "Reader", exact: true }),
	).toBeVisible();
	await expectAccessible(page);

	// The transcript is a few lines high. Words typed into the open channel
	// fill it past that, and it follows its newest line: in view, where a
	// line the box has scrolled away is still "visible".
	const typing = page.getByRole("textbox", {
		name: "Type to the voice channel…",
	});
	for (const line of TYPED) {
		await typing.fill(line);
		await typing.press("Enter");
		await expect(pane.getByText(line)).toBeInViewport();
	}
	const said = pane.getByRole("log", { name: "What was said" });
	expect(
		await said.evaluate((box) => box.scrollHeight > box.clientHeight),
	).toBe(true);
	await expect(pane.getByText(ASKED)).not.toBeInViewport();
	// Each line says whose it is, and the box — scrolling now — can be reached and has a name.
	await expect(said.getByText("You said:").first()).toBeAttached();
	await expect(said.getByText("The assistant said:")).toBeAttached();
	await expectAccessible(page);

	await pane.getByRole("button", { name: "Close the channel" }).click();
	await expect(pane).toHaveCount(0);
	await expect(composer(page)).toBeVisible();
	// The backend wrote the spoken turns into the thread; the chat reads them with no reload.
	await expect(page.getByText(ASKED)).toBeVisible();
	await expect(
		page.getByRole("paragraph").filter({ hasText: ANSWERED }),
	).toBeVisible();
});

/**
 * One edge, never two. Without Front Door the Container Apps ingress is the
 * public origin and no profile exists; with it, the environment's public
 * ingress is closed and the profile's origin reaches it over a private link,
 * behind a WAF in prevention mode. Neither setting leaves the origin open
 * beside an edge.
 */
import { expect, test } from "bun:test";
import {
	allResources,
	compiledMain,
	sampleDeployment,
	type Template,
} from "./arm";

const it = test.skipIf(compiledMain() === null);

function shape(useFrontDoor: boolean) {
	const d = sampleDeployment({ useFrontDoor: String(useFrontDoor) });
	if (!d) throw new Error("no template");
	const live = allResources(d).filter((r) => r.condition);
	const environment = live.find(
		(r) => r.type === "Microsoft.App/managedEnvironments",
	);
	const frontend = live.find(
		(r) =>
			r.type === "Microsoft.App/containerApps" &&
			(r.tags as Record<string, string>)["azd-service-name"] === "frontend",
	);
	if (!environment || !frontend) throw new Error("no environment or frontend");
	const frontendEnv = Object.fromEntries(
		(
			frontend.properties as {
				template: {
					containers: { env: { name: string; value?: unknown }[] }[];
				};
			}
		).template.containers[0].env.map((e) => [e.name, e.value]),
	);
	return {
		frontendEnv,
		profiles: live.filter((r) => r.type === "Microsoft.Cdn/profiles"),
		endpoints: live.filter(
			(r) => r.type === "Microsoft.Cdn/profiles/afdEndpoints",
		),
		origins: live.filter(
			(r) => r.type === "Microsoft.Cdn/profiles/originGroups/origins",
		),
		wafs: live.filter(
			(r) =>
				r.type === "Microsoft.Network/FrontDoorWebApplicationFirewallPolicies",
		),
		publicNetworkAccess: (
			environment.properties as { publicNetworkAccess: string }
		).publicNetworkAccess,
		frontendIngress: (
			frontend.properties as {
				configuration: { ingress: { external: boolean } };
			}
		).configuration.ingress,
	};
}

it("by default the ingress is the edge and nothing else is provisioned", () => {
	const s = shape(false);
	expect(s.profiles).toEqual([]);
	expect(s.origins).toEqual([]);
	expect(s.wafs).toEqual([]);
	expect(s.publicNetworkAccess).toBe("Enabled");
	expect(s.frontendIngress.external).toBe(true);
});

it("with Front Door the origin is sealed behind its private link and a WAF", () => {
	const s = shape(true);
	expect(s.profiles).toHaveLength(1);
	expect(s.publicNetworkAccess).toBe("Disabled");
	expect(s.frontendIngress.external).toBe(true);
	expect(s.origins).toHaveLength(1);
	const origin = s.origins[0].properties as {
		sharedPrivateLinkResource: {
			groupId: string;
			privateLink: { id: unknown };
		};
	};
	expect(origin.sharedPrivateLinkResource.groupId).toBe("managedEnvironments");
	expect(origin.sharedPrivateLinkResource.privateLink.id).toBeTruthy();
	expect(s.wafs).toHaveLength(1);
	expect(
		(s.wafs[0].properties as { policySettings: { mode: string } })
			.policySettings.mode,
	).toBe("Prevention");
	// The module's default ApplyGeoFilter rule answers every request 403;
	// the managed rule sets are the WAF.
	expect(
		(s.wafs[0].properties as { customRules: { rules: unknown[] } }).customRules
			.rules,
	).toEqual([]);
});

it("the WAF reads no bodies, and every rule blocks: 920420 too", () => {
	// With bodies inspected, 942200 refuses prose in a chat's JSON body. No
	// route sends a body 920420 refuses (live voice is one WebSocket), so it
	// blocks like every other rule.
	const waf = shape(true).wafs[0].properties as {
		policySettings: { mode: string; requestBodyCheck: string };
		customRules: { rules: unknown[] };
		managedRules: {
			managedRuleSets: {
				ruleSetType: string;
				ruleSetVersion: string;
				ruleSetAction?: string;
				ruleGroupOverrides: unknown[];
			}[];
		};
	};
	expect(waf.policySettings.mode).toBe("Prevention");
	expect(waf.policySettings.requestBodyCheck).toBe("Disabled");
	expect(waf.customRules.rules).toEqual([]);
	const sets = waf.managedRules.managedRuleSets;
	expect(sets.map((r) => `${r.ruleSetType}@${r.ruleSetVersion}`)).toEqual([
		"Microsoft_DefaultRuleSet@2.1",
		"Microsoft_BotManagerRuleSet@1.0",
	]);
	expect(sets[0].ruleSetAction).toBe("Block");
	expect(sets[0].ruleGroupOverrides).toEqual([]);
});

it("the endpoint's host label is reused per resource group, never per tenant", () => {
	// Azure's default scope, TenantReuse, gives the same endpoint name in the
	// same tenant the same azurefd.net host: a second hardened provision in a
	// tenant is refused, at the end of the provision, with "That resource name
	// isn't available" on the endpoint, while the first deployment holds the host.
	const endpoints = shape(true).endpoints;
	expect(endpoints).toHaveLength(1);
	expect(
		(
			endpoints[0].properties as {
				autoGeneratedDomainNameLabelScope?: string;
			}
		).autoGeneratedDomainNameLabelScope,
	).toBe("ResourceGroupReuse");
});

it("no edge output reads the profile at the deployment's start", () => {
	// ARM resolves reference() to a resource its template does not deploy
	// when the deployment starts, so a hardened provision would fail with
	// ResourceNotFound on the profile it is about to create.
	const deployments = (t: Template) =>
		Object.values(t.resources ?? {}).filter(
			(r) => r.type === "Microsoft.Resources/deployments",
		) as { name: string; properties: { template: Template } }[];
	const edge = deployments(compiledMain() as Template).find(
		(r) => r.name === "edge",
	);
	if (!edge) throw new Error("no edge deployment");
	const outputs = Object.values(edge.properties.template.outputs ?? {});
	for (const output of outputs)
		expect(String(output.value)).not.toMatch(
			/reference\(resourceId\('Microsoft\.Cdn/,
		);
});

it("the frontend signs in at the edge from the first provision, and no output feeds the override back", () => {
	// The template sets the address itself: a hook that recorded it would
	// leave the first provision's AUTH_URL on the sealed ingress, and an
	// output named after the override would come back as one on the next
	// provision.
	expect(String(shape(true).frontendEnv.AUTH_URL)).toMatch(/endpointHost/);
	expect(String(shape(false).frontendEnv.AUTH_URL)).not.toMatch(/endpointHost/);
	expect(Object.keys(compiledMain()?.outputs ?? {})).not.toContain(
		"PUBLIC_ORIGIN",
	);
});
